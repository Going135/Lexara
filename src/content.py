def bubble_for(key: str) -> str:
    pool = LINES.get(key)
    return random.choice(pool) if pool else ""


#: 识词完成后，按挑中数量挑一条播报
OCR_DONE_LINES = (
    "挑出 {n} 个词，八条腿够用了。",
    "找到 {n} 个，我踩给你看。",
    "{n} 个词，收好了。",
)


def ocr_done(count: int) -> str:
    return random.choice(OCR_DONE_LINES).format(n=count)


